-- Run inside a transaction after the migration, then ROLLBACK. No real bills or stock changes remain.
do $$
declare b uuid; owner_id uuid; staff_id uuid; h uuid; d uuid; tea uuid; mix uuid; brew uuid; r uuid; tr uuid;
 token text:=gen_random_uuid()::text; staff_token text:=gen_random_uuid()::text;
 oid uuid; cid uuid:=gen_random_uuid(); lm_id uuid:=gen_random_uuid(); wid uuid:=gen_random_uuid();
 payload jsonb; moves jsonb; result jsonb; retry jsonb; rejected boolean; n bigint;
begin
 insert into public.branches(name) values('Auto prep QA rollback') returning id into b;
 insert into public.users(name,role,branch_id) values('Auto prep QA owner','owner',b) returning id into owner_id;
 insert into public.users(name,role,branch_id) values('Auto prep QA staff','staff',b) returning id into staff_id;
 insert into public.pin_sessions(user_id,token_hash) values(owner_id,encode(extensions.digest(token,'sha256'),'hex')),(staff_id,encode(extensions.digest(staff_token,'sha256'),'hex'));
 insert into public.ingredients(name,unit,stock_qty,cost_per_unit) values('QA Hooray','g',1000,1) returning id into h;
 insert into public.ingredients(name,unit,stock_qty,cost_per_unit) values('QA Do it','g',1000,2) returning id into d;
 insert into public.ingredients(name,unit,stock_qty,cost_per_unit) values('QA dry tea','g',1000,3) returning id into tea;
 insert into public.ingredients(name,unit,stock_qty,cost_per_unit) values('QA protein mix','g',0,0) returning id into mix;
 insert into public.ingredients(name,unit,stock_qty,cost_per_unit) values('QA brewed tea','ml',0,0) returning id into brew;
 insert into public.production_recipes(id,branch_id,name,output_id,output_unit,expected_qty,deduction_mode) values(gen_random_uuid(),b,'QA protein',mix,'g',300,'sale') returning id into r;
 insert into public.production_recipe_inputs values(r,h,180,'g',1,'g'),(r,d,120,'g',1,'g');
 insert into public.production_recipes(id,branch_id,name,output_id,output_unit,expected_qty,deduction_mode) values(gen_random_uuid(),b,'QA tea',brew,'ml',200,'sale') returning id into tr;
 insert into public.production_recipe_inputs values(tr,tea,5,'g',1,'g');
 perform private.refresh_auto_prep_costs();
 assert (select cost_per_unit=1.4 from public.ingredients where id=mix),'wrong composite cost';
 assert (select cost_per_unit=0.075 from public.ingredients where id=brew),'wrong tea cost';
 perform set_config('request.jwt.claim.sub',gen_random_uuid()::text,true);
 moves:=jsonb_build_array(jsonb_build_object('ingredient_id',mix,'type','sale','qty_delta',-30),jsonb_build_object('ingredient_id',brew,'type','sale','qty_delta',-100));
 set local role authenticated;
 perform public.submit_order(cid,b,owner_id,'dine_in',0,0,0,0,'QA','[]','[]',moves);
 perform public.submit_order(cid,b,owner_id,'dine_in',0,0,0,0,'QA','[]','[]',moves);
 reset role;
 select id into oid from public.orders where client_uuid=cid;
 assert (select stock_qty=982 from public.ingredients where id=h),'protein Hooray deduction/retry';
 assert (select stock_qty=988 from public.ingredients where id=d),'protein Do it deduction/retry';
 assert (select stock_qty=997.5 from public.ingredients where id=tea),'tea deduction/retry';
 assert (select stock_qty=0 from public.ingredients where id=mix),'virtual mix changed';
 assert (select stock_qty=0 from public.ingredients where id=brew),'virtual tea changed';
 assert (select count(*)=5 from public.stock_movements where ref_order_id=oid),'wrong expanded ledger';
 assert private.daily_tea_used(b,(now() at time zone 'Asia/Bangkok')::date,brew)=100,'tea marker missing from report';
 -- Recipe edits do not change restoration of a new bill's actual raw movements.
 update public.production_recipe_inputs set input_qty=150 where recipe_id=r;
 perform public.void_order(oid,owner_id);
 perform public.void_order(oid,owner_id);
 assert (select stock_qty=1000 from public.ingredients where id=h),'void failed to restore exact Hooray amount';
 assert (select stock_qty=1000 from public.ingredients where id=d),'void failed to restore exact Do it amount';
 assert (select stock_qty=1000 from public.ingredients where id=tea),'void failed to restore exact tea amount';
 assert private.daily_tea_used(b,(now() at time zone 'Asia/Bangkok')::date,brew)=0,'void tea still counted';
 update public.production_recipe_inputs set input_qty=180 where recipe_id=r and ingredient_id=h;
 update public.production_recipe_inputs set input_qty=120 where recipe_id=r and ingredient_id=d;
 -- Current LINE MAN operational path (no prices) shares automatic expansion.
 payload:=jsonb_build_object('client_uuid',lm_id,'reference','QA-'||left(lm_id::text,8),'items',jsonb_build_array(jsonb_build_object('name_snapshot','QA Protein','qty',1,'recipe','[]'::jsonb)), 'stock_movements',moves);
 set local role authenticated;
 result:=public.record_line_man_order(token,payload);
 retry:=public.record_line_man_order(token,payload);
 reset role;
 assert result=retry,'LINE MAN retry result changed';
 assert (select stock_qty=982 from public.ingredients where id=h),'LINE MAN Hooray';
 assert (select stock_qty=988 from public.ingredients where id=d),'LINE MAN Do it';
 assert (select stock_qty=997.5 from public.ingredients where id=tea),'LINE MAN tea';
 -- Explicit daily/weekly waste records and idempotent retry.
 payload:=jsonb_build_object('id',wid,'ingredient_id',mix,'unit','g','qty',50,'business_date',(now() at time zone 'Asia/Bangkok')::date,'reason','QA leftover');
 set local role authenticated;
 result:=public.production_action(staff_token,'waste',payload);
 retry:=public.production_action(staff_token,'waste',payload);
 reset role;
 assert result=retry,'waste retry changed';
 assert (select stock_qty=952 from public.ingredients where id=h),'waste Hooray';
 assert (select stock_qty=968 from public.ingredients where id=d),'waste Do it';
 assert (result->>'total_cost')::numeric=70,'wrong waste cost';
 rejected:=false;
 begin perform public.production_action(staff_token,'cancel_waste',jsonb_build_object('id',wid,'reason','QA')); exception when others then rejected:=true; end;
 assert rejected,'staff cancelled waste';
 perform public.production_action(token,'cancel_waste',jsonb_build_object('id',wid,'reason','QA'));
 perform public.production_action(token,'cancel_waste',jsonb_build_object('id',wid,'reason','QA retry'));
 assert (select stock_qty=982 from public.ingredients where id=h),'waste reversal/retry Hooray';
 assert (select stock_qty=988 from public.ingredients where id=d),'waste reversal/retry Do it';
 rejected:=false;
 begin perform public.production_action(token,'waste',payload||jsonb_build_object('qty',20)); exception when others then rejected:=true; end;
 assert rejected,'changed idempotency payload accepted';
 rejected:=false;
 begin perform public.production_action(token,'waste',payload||jsonb_build_object('id',gen_random_uuid(),'qty',-1)); exception when others then rejected:=true; end;
 assert rejected,'negative waste accepted';
 rejected:=false;
 begin perform public.production_action(token,'produce',jsonb_build_object('recipe_id',r)); exception when others then rejected:=true; end;
 assert rejected,'automatic recipe double produced';
 rejected:=false;
 begin perform public.daily_tea_action(token,'settings','{"grams_per_spoon":5}'); exception when others then rejected:=true; end;
 assert rejected,'legacy daily tea deducted twice';
 perform set_config('request.jwt.claim.sub','',true);
 rejected:=false;
 begin perform public.production_action(token,'load','{}'); exception when others then rejected:=true; end;
 assert rejected,'anonymous waste access';
 assert not has_function_privilege('anon','public.get_auto_prep_recipes()','execute'),'anonymous auto recipe grant';
end $$;
select 'PASS: raw deductions, tea reporting, retail/Grab shared RPC, LINE MAN, retries, exact void restoration, waste costs/reversal, PIN and auth; fixtures rolled back.' as result;
