-- Run inside BEGIN/ROLLBACK; creates isolated fixtures and changes no live recipe settings.
do $$
declare b uuid; owner_id uuid; staff_id uuid; h uuid; d uuid; mix uuid; rid uuid:=gen_random_uuid();
 token text:=gen_random_uuid()::text; staff_token text:=gen_random_uuid()::text; payload jsonb; saved jsonb;
 cid uuid:=gen_random_uuid(); oid uuid; wid uuid:=gen_random_uuid(); rejected boolean;
 before_h numeric; before_d numeric;
begin
 insert into public.branches(name) values('Selectable prep QA rollback') returning id into b;
 insert into public.users(name,role,branch_id) values('Mode QA owner','owner',b) returning id into owner_id;
 insert into public.users(name,role,branch_id) values('Mode QA staff','staff',b) returning id into staff_id;
 insert into public.pin_sessions(user_id,token_hash) values(owner_id,encode(extensions.digest(token,'sha256'),'hex')),(staff_id,encode(extensions.digest(staff_token,'sha256'),'hex'));
 insert into public.ingredients(name,unit,stock_qty,cost_per_unit) values('Mode QA A','g',1000,1) returning id into h;
 insert into public.ingredients(name,unit,stock_qty,cost_per_unit) values('Mode QA B','g',1000,2) returning id into d;
 insert into public.ingredients(name,unit,stock_qty,cost_per_unit) values('Mode QA mixed','g',300,1.4) returning id into mix;
 perform set_config('request.jwt.claim.sub',gen_random_uuid()::text,true);
 payload:=jsonb_build_object('id',rid,'revision',0,'name','Mode QA blend','output_id',mix,'expected_qty',300,'deduction_mode','produce','items',jsonb_build_array(jsonb_build_object('ingredient_id',h,'input_qty',180,'input_unit','g'),jsonb_build_object('ingredient_id',d,'input_qty',120,'input_unit','g')));
 set local role authenticated;
 perform public.production_action(token,'save_recipe',payload);
 payload:=payload||jsonb_build_object('revision',1,'deduction_mode','sale','mode_stock_qty',300);
 perform public.production_action(token,'save_recipe',payload);
 reset role;
 assert (select deduction_mode='sale' and revision=2 from public.production_recipes where id=rid),'mode not saved';
 assert (select stock_qty=1180 from public.ingredients where id=h),'production to sale A conversion';
 assert (select stock_qty=1120 from public.ingredients where id=d),'production to sale B conversion';
 assert (select stock_qty=0 and daily_prep from public.ingredients where id=mix),'production to sale output';
 rejected:=false;
 begin perform public.production_action(token,'save_recipe',payload); exception when others then rejected:=true; end;
 assert rejected,'stale mode save accepted';
 perform public.submit_order(gen_random_uuid(),b,owner_id,'dine_in',0,0,0,0,'QA','[]','[]',jsonb_build_array(jsonb_build_object('ingredient_id',mix,'type','sale','qty_delta',-30)));
 assert (select stock_qty=1162 from public.ingredients where id=h),'sale A';
 assert (select stock_qty=1108 from public.ingredients where id=d),'sale B';
 payload:=payload||jsonb_build_object('revision',2,'deduction_mode','produce','mode_stock_qty',0,'opening_qty',60);
 set local role authenticated;
 perform public.production_action(token,'save_recipe',payload);
 reset role;
 assert (select stock_qty=1126 from public.ingredients where id=h),'sale to production A';
 assert (select stock_qty=1084 from public.ingredients where id=d),'sale to production B';
 assert (select stock_qty=60 and not daily_prep from public.ingredients where id=mix),'sale to production opening stock';
 perform public.submit_order(cid,b,owner_id,'dine_in',0,0,0,0,'QA','[]','[]',jsonb_build_array(jsonb_build_object('ingredient_id',mix,'type','sale','qty_delta',-10)));
 assert (select stock_qty=50 from public.ingredients where id=mix),'production mode sale did not use output stock';
 assert (select stock_qty=1126 from public.ingredients where id=h),'production mode double cut A';
 select id into oid from public.orders where client_uuid=cid;
 assert exists(select 1 from public.stock_movements where ref_order_id=oid and prep_return_inputs is not null),'prepared sale lost snapshot';
 payload:=payload||jsonb_build_object('revision',3,'deduction_mode','sale','mode_stock_qty',50);
 perform public.production_action(token,'save_recipe',payload);
 assert (select stock_qty=1156 from public.ingredients where id=h),'second production to sale A';
 assert (select stock_qty=1104 from public.ingredients where id=d),'second production to sale B';
 -- Freeze old input returns even when ratios subsequently change.
 update public.production_recipe_inputs set input_qty=150 where recipe_id=rid;
 perform public.void_order(oid,owner_id);
 perform public.void_order(oid,owner_id);
 assert (select stock_qty=1162 from public.ingredients where id=h),'void across modes did not use A snapshot';
 assert (select stock_qty=1108 from public.ingredients where id=d),'void across modes did not use B snapshot';
 assert (select stock_qty=0 from public.ingredients where id=mix),'void stranded virtual output';
 update public.production_recipe_inputs set input_qty=180 where recipe_id=rid and ingredient_id=h;
 update public.production_recipe_inputs set input_qty=120 where recipe_id=rid and ingredient_id=d;
 payload:=payload||jsonb_build_object('revision',4,'deduction_mode','produce','mode_stock_qty',0,'opening_qty',50);
 perform public.production_action(token,'save_recipe',payload);
 perform public.production_action(staff_token,'waste',jsonb_build_object('id',wid,'ingredient_id',mix,'qty',10,'unit','g','business_date',(now() at time zone 'Asia/Bangkok')::date,'reason','QA prepared waste'));
 assert (select stock_qty=40 from public.ingredients where id=mix),'prepared waste not deducted';
 payload:=payload||jsonb_build_object('revision',5,'deduction_mode','sale','mode_stock_qty',40);
 perform public.production_action(token,'save_recipe',payload);
 perform public.production_action(token,'cancel_waste',jsonb_build_object('id',wid,'reason','QA'));
 perform public.production_action(token,'cancel_waste',jsonb_build_object('id',wid,'reason','QA retry'));
 assert (select stock_qty=1162 from public.ingredients where id=h),'waste reversal across modes A';
 assert (select stock_qty=1108 from public.ingredients where id=d),'waste reversal across modes B';
 assert (select stock_qty=0 from public.ingredients where id=mix),'waste reversal stranded virtual output';
 -- Shortage must roll back the entire transition.
 select stock_qty into before_h from public.ingredients where id=h;
 select stock_qty into before_d from public.ingredients where id=d;
 rejected:=false;
 begin perform public.production_action(token,'save_recipe',payload||jsonb_build_object('revision',6,'deduction_mode','produce','mode_stock_qty',0,'opening_qty',1000000)); exception when others then rejected:=true; end;
 assert rejected,'shortage switch accepted';
 assert (select deduction_mode='sale' and revision=6 from public.production_recipes where id=rid),'failed switch changed mode or revision';
 assert (select stock_qty=before_h from public.ingredients where id=h) and (select stock_qty=before_d from public.ingredients where id=d),'failed switch changed stock';
 rejected:=false;
 begin perform public.production_action(staff_token,'save_recipe',payload||jsonb_build_object('revision',6)); exception when others then rejected:=true; end;
 assert rejected,'staff changed deduction mode';
 -- Older clients omit deduction_mode: preserve the selected mode with no stock transfer.
 perform public.production_action(token,'save_recipe',(payload-'deduction_mode'-'mode_stock_qty'-'opening_qty')||jsonb_build_object('revision',6));
 assert (select deduction_mode='sale' from public.production_recipes where id=rid),'legacy save reset mode';
 assert (select count(*)=5 from public.audit_log where entity_id=rid and action='change_deduction_mode'),'mode audit trail incomplete';
end $$;
select 'PASS: per-recipe selection, both stock transfers, no double deductions, stale retry protection, prepared sales/waste reversal across switches, shortages, legacy clients, permissions and audit trail.' result;
